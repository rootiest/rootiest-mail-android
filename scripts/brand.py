#!/usr/bin/env python3
"""brand.py [--check] [--icons DIR]: generate the Rootiest Mail resource overrides in android/app/src/rootiest/res.

The rootiest build flavor (android/app/rootiest.gradle) replaces upstream resources by giving them the same name in
its own source set, so upstream's files stay untouched and merging a new Bulwark Mobile release stays cheap. This
script writes those overrides; after each upstream merge run it and review `git diff`:

- values/strings.xml: the app's name, the launcher's short label (android/app/src/rootiest/AndroidManifest.xml), and
  the label of its device-sync account in Android's settings.
- locales/rootiest/strings.json: the app's strings that name Bulwark, in every language, naming Rootiest Mail
  instead. src/i18n merges them over upstream's catalogs in the rootiest build. Each language's own translation is
  kept and only the name is swapped, so a string upstream adds or rewords is picked up on the next run.
- values{,-night}/colors.xml: the launch screen's and the window's background, the theme's page colour.
- src/theme/rootiest-theme.ts: the Rootiest theme (Catppuccin Mocha with the green accent, Latte with flamingo), from
  the stylesheet rootiest-icons generates for the webmail (icons/themes/bulwark.css), so the app and the webmail
  share one palette. Its id is the webmail theme's, so the webmail policy's default theme picks it here too.
- drawable/ic_launcher_*.xml and mipmap-anydpi-v26/: the adaptive launcher icon, from rootiest-icons
  icons/color/rootiest-mail.svg (the swirl and the mail emblem) on Catppuccin Mocha base, with a themed
  (monochrome) layer.
- drawable/ic_notification.xml: the status-bar icon, the same shapes in white.
- mipmap-*/ic_launcher*.webp: the launcher icon as pictures, for Android 7 (before adaptive icons).
- drawable-xxxhdpi/splashscreen_logo.png: the logo on the launch screen.
- assets/rootiest/logo-{dark,light}.png: the logo in the app (sign-in, About), for dark and light backgrounds; the light
  one has the icon's darker light-mode emblem.

DIR defaults to ../rootiest-icons; the icons are skipped if it is absent. The pictures need rsvg-convert, ImageMagick and cwebp.

--check writes nothing and exits 1 if any generated text file is missing or out of date (the pictures are left
out: encoders differ between machines).
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_RES = ROOT / "android/app/src/rootiest/res"
ICON = "icons/color/rootiest-mail.svg"
THEME_CSS = "icons/themes/bulwark.css"
OUT_THEME = ROOT / "src/theme/rootiest-theme.ts"

NAME = "Rootiest Mail"
# Under the launcher icon, where "Rootiest Mail" is cut off; the full name stays everywhere else.
LAUNCHER_LABEL = "Mail"

LOCALES = ROOT / "locales"
OUT_LOCALES = LOCALES / "rootiest/strings.json"
# The app's name in upstream's strings; "Bulwark Mail" and "Bulwark Mobile" are names of the same app.
APP_NAME_PATTERN = re.compile(r"Bulwark(?: Mail| Mobile)?")
# Strings where Bulwark names something other than the app, so it becomes Rootiest: the push relay (the app
# defaults to Rootiest's own) and Bulwark Files (the account's file storage).
ROOTIEST_ONLY = {
    "settings.notifications.push.description_mobile",
    "settings.notifications.push.relay_desc_mobile",
    "email_composer.attach_bulwark_files",
}
# Strings that name Bulwark on purpose, because they mean upstream itself (Settings > About's "Based on Bulwark
# Mobile"): left as they are.
KEEP_BULWARK = {
    "settings.about.based_on_bulwark",
}
# A key the app reads: t('key' ...) anywhere in src outside the tests.
USED_KEY = re.compile(r"""\bt\(\s*['"]([a-zA-Z0-9_.-]+)['"]""")

GENERATED = "Generated by scripts/brand.py from {source}. Do not edit; rerun the script."

# The launcher icon: Catppuccin Mocha base behind the icon, which fills 64 of the adaptive icon's 108 dp.
ICON_BACKGROUND = "#1E1E2E"
ICON_SIZE = 64.0
CANVAS = 108.0
# The status-bar icon: 22 of its 24 dp, Android's live area for small icons.
SMALL_SIZE = 22.0
SMALL_CANVAS = 24.0
# Legacy launcher pictures per density (48 dp), and the splash logo (upstream's size).
LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
SPLASH_SIZE = 1152
LOGO_SIZE = 512
OUT_ASSETS = ROOT / "assets/rootiest"
# ImageMagick stamps PNGs with the time they were written; without it a rerun leaves them unchanged.
STABLE_PNG = ["-strip", "-define", "png:exclude-chunk=date,time"]
SVG_NS = {"svg": "http://www.w3.org/2000/svg"}


def xml_note(text: str) -> str:
    return f"<!-- {text} -->\n"


# ── Strings ───────────────────────────────────────────────────────────────────────────────────────────────────────


def string_outputs() -> dict[Path, str]:
    source = "the app name in this script"
    text = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + xml_note(GENERATED.format(source=source))
        + "<resources>\n"
        f'  <string name="app_name">{NAME}</string>\n'
        "  <!-- The launcher's label, under the icon. -->\n"
        f'  <string name="launcher_label">{LAUNCHER_LABEL}</string>\n'
        "  <!-- Account type label of device sync, shown in Settings → Accounts. -->\n"
        f'  <string name="device_sync_account_label" translatable="false">{NAME}</string>\n'
        "</resources>\n"
    )
    return {OUT_RES / "values/strings.xml": text}


# ── Locales ───────────────────────────────────────────────────────────────────────────────────────────────────


def flatten(tree: dict, prefix: str = "") -> dict[str, str]:
    out = {}
    for key, value in tree.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out |= flatten(value, path)
        elif isinstance(value, str):
            out[path] = value
    return out


def nest(flat: dict[str, str]) -> dict:
    tree: dict = {}
    for path, value in sorted(flat.items()):
        node = tree
        *parents, leaf = path.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        node[leaf] = value
    return tree


def catalog(lang: str) -> dict[str, str]:
    """A language's strings as the app merges them: the web catalog, then the app's own over it."""
    import json

    web = LOCALES / lang / "common.json"
    app = LOCALES / "rn" / f"{lang}.json"
    merged = flatten(json.loads(web.read_text(encoding="utf-8"))) if web.is_file() else {}
    return merged | flatten(json.loads(app.read_text(encoding="utf-8")))


def locale_outputs() -> dict[Path, str]:
    import json

    used = set()
    for source in (ROOT / "src").rglob("*.ts*"):
        if "__tests__" not in source.parts:
            used |= set(USED_KEY.findall(source.read_text(encoding="utf-8", errors="ignore")))
    english = catalog("en")
    app_keys = set(flatten(json.loads((LOCALES / "rn/en.json").read_text(encoding="utf-8"))))
    # The app's own strings, and the web ones it reads, that name Bulwark.
    keys = {k for k, v in english.items() if "Bulwark" in v and (k in used or k in app_keys) and k not in KEEP_BULWARK}

    langs = sorted(p.stem for p in (LOCALES / "rn").glob("*.json"))
    result = {}
    for lang in langs:
        strings = catalog(lang)
        changed = {}
        for key in keys:
            text = strings.get(key)
            # A translation without the name keeps its own wording.
            if not text or "Bulwark" not in text:
                continue
            changed[key] = (
                text.replace("Bulwark", "Rootiest") if key in ROOTIEST_ONLY else APP_NAME_PATTERN.sub(NAME, text)
            )
        result[lang] = nest(changed)
    note = GENERATED.format(source="locales/*/common.json and locales/rn/*.json")
    text = json.dumps({"_comment": note, **result}, ensure_ascii=False, indent=2, sort_keys=False) + "\n"
    return {OUT_LOCALES: text}


# ── Theme ─────────────────────────────────────────────────────────────────────────────────────────────────────

# The webmail's colour variables -> the app's palette tokens, as src/theme/builtin-themes.ts maps the webmail themes.
THEME_MAP = {
    "primary": ["primary", "primaryDark", "textLink", "navActive"],
    "primary-foreground": ["primaryForeground"],
    "ring": ["primaryLight", "borderFocus"],
    "accent": ["accent", "primaryBg", "primaryBgHover", "surfaceHover"],
    "accent-foreground": ["accentForeground"],
    "secondary": ["secondary", "surface"],
    "secondary-foreground": ["secondaryForeground"],
    "muted": ["muted", "surfaceActive"],
    "muted-foreground": ["mutedForeground", "textSecondary", "textMuted", "read", "navInactive"],
    "foreground": ["text"],
    "background": ["background", "textInverse"],
    "card": ["card"],
    "card-foreground": ["cardForeground"],
    "popover": ["popover"],
    "popover-foreground": ["popoverForeground"],
    "border": ["border", "borderLight"],
    "destructive": ["error", "navBadge"],
    "destructive-foreground": ["errorForeground"],
    "success": ["success"],
    "success-foreground": ["successForeground"],
    "warning": ["warning"],
    "warning-foreground": ["warningForeground"],
    "info": ["info"],
    "info-foreground": ["infoForeground"],
    "selection": ["selection"],
    "selection-foreground": ["selectionForeground"],
    "unread": ["unread"],
    **{f"chart-{n}": [f"chart{n}"] for n in range(1, 6)},
}
THEME_ID = "rootiest"
# Where the app parts from the webmail's colours, for the 4.5:1 that src/theme/__tests__/theme-contrast.test.ts asks
# of muted text on every ground (as upstream's own Catppuccin port does): Latte subtext0 (#6c6f85) reaches 4.37:1 on
# base, so muted text is subtext1; and the webmail lays muted (surface0) at 30-50% over the page where the app paints
# it solid, so muted is crust.
THEME_FIXES = {"light": {"muted-foreground": "#5c5f77", "muted": "#dce0e8"}, "dark": {}}


def css_block(css: str, selector: str) -> dict[str, str]:
    """A selector's --color-* variables; a later one wins, as in the browser."""
    match = re.search(re.escape(selector) + r"\s*\{(.*?)\}", css, re.S)
    if not match:
        sys.exit(f"brand.py: no {selector} block in {THEME_CSS}")
    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)
    return dict(re.findall(r"--color-([a-z0-9-]+)\s*:\s*([^;]+?)\s*;", body))


def hex_rgb(value: str) -> tuple[int, ...]:
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        sys.exit(f"brand.py: unexpected colour {value!r} in {THEME_CSS}")
    return tuple(int(value[i : i + 2], 16) for i in (1, 3, 5))


def solid_colour(value: str, background: str) -> str:
    """A colour as #rrggbb; color-mix() is worked out, and transparent means the page behind it (RN has no blending
    of its own here, as builtin-themes.ts notes)."""
    mix = re.fullmatch(r"color-mix\(in srgb,\s*(#[0-9a-fA-F]{6})\s+([\d.]+)%,\s*(#[0-9a-fA-F]{6}|transparent)\)", value)
    if not mix:
        hex_rgb(value)
        return value.lower()
    first, share, second = mix.group(1), float(mix.group(2)) / 100, mix.group(3)
    a, b = hex_rgb(first), hex_rgb(background if second == "transparent" else second)
    return "#" + "".join(f"{round(x * share + y * (1 - share)):02x}" for x, y in zip(a, b))


def theme_outputs(icons: Path) -> dict[Path, str]:
    css = (icons / THEME_CSS).read_text(encoding="utf-8")
    modes = {"light": css_block(css, ":root"), "dark": css_block(css, ".dark")}
    lines = [
        f"// {GENERATED.format(source='rootiest-icons ' + THEME_CSS)}",
        "// The Rootiest theme: the palette of the webmail's Rootiest theme, mapped onto the app's tokens as",
        "// builtin-themes.ts maps the webmail themes. Listed first in the rootiest build, and its default.",
        "import type { BuiltinTheme } from './builtin-themes';",
        "",
        "export const ROOTIEST_THEME: BuiltinTheme = {",
        f"  id: '{THEME_ID}',",
        "  name: 'Rootiest',",
        "  description: 'The Rootiest palette: Catppuccin Mocha with the green accent, and Latte with flamingo',",
    ]
    for mode, variables in modes.items():
        variables = variables | THEME_FIXES[mode]
        background = variables["background"]
        lines.append(f"  {mode}: {{")
        for var, tokens in THEME_MAP.items():
            if var not in variables:
                sys.exit(f"brand.py: {THEME_CSS} has no --color-{var} for {mode}")
            colour = solid_colour(variables[var], background)
            lines += [f"    {token}: '{colour}'," for token in tokens]
        lines.append("  },")
    lines += ["};", ""]
    outputs = {OUT_THEME: "\n".join(lines)}
    # The launch screen and the window behind the first frame, in the theme's page colour, so opening the app doesn't
    # flash upstream's white or near-black.
    for mode, folder in (("light", "values"), ("dark", "values-night")):
        page = solid_colour(modes[mode]["background"], "#000000")
        outputs[OUT_RES / folder / "colors.xml"] = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            + xml_note(GENERATED.format(source="rootiest-icons " + THEME_CSS))
            + "<resources>\n"
            f'  <color name="splashscreen_background">{page}</color>\n'
            f'  <color name="window_background">{page}</color>\n'
            "</resources>\n"
        )
    return outputs


# ── Icons ─────────────────────────────────────────────────────────────────────────────────────────────────────────


def svg_color(svg_text: str, cls: str) -> str:
    match = re.search(r"\.ColorScheme-" + cls + r"\{color:#([0-9a-fA-F]{6})\}", svg_text)
    if not match:
        sys.exit(f"brand.py: no ColorScheme-{cls} color in the icon")
    return "#FF" + match.group(1).upper()


def child(parent: ET.Element, path: str) -> ET.Element:
    found = parent.find(path, SVG_NS)
    if found is None:
        sys.exit(f"brand.py: the icon has no {path}; has its layout changed?")
    return found


def attr(element: ET.Element, name: str) -> str:
    value = element.get(name)
    if value is None:
        sys.exit(f"brand.py: the icon's {element.tag} has no {name}; has its layout changed?")
    return value


def icon_outputs(icons: Path) -> dict[Path, str]:
    source = icons / ICON
    origin_note = GENERATED.format(source="rootiest-icons " + ICON)
    svg_text = source.read_text(encoding="utf-8")
    svg = ET.fromstring(svg_text)
    full = child(svg, "svg:g[@class='SizeFull']")
    swirl = attr(child(full, "svg:path"), "d")
    emblem_group = child(full, "svg:g")
    emblem = attr(child(emblem_group, "svg:path"), "d")
    tx, ty, scale = map(float, re.findall(r"-?[0-9.]+", attr(emblem_group, "transform")))
    min_x, min_y, width, _ = map(float, attr(svg, "viewBox").split())

    def vector(what: str, size: float, canvas: float, swirl_color: str, emblem_color: str) -> str:
        fit = size / width
        offset = (canvas - size) / 2
        return (
            xml_note(f"{what} {origin_note}")
            + xml_note("The swirl's long path is fine here: Android draws the icon once and caches it.")
            + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:tools="http://schemas.android.com/tools" tools:ignore="VectorPath"\n'
            f'    android:width="{canvas:g}dp" android:height="{canvas:g}dp"\n'
            f'    android:viewportWidth="{canvas:g}" android:viewportHeight="{canvas:g}">\n'
            f'    <group android:translateX="{offset - min_x * fit:.4f}" android:translateY="{offset - min_y * fit:.4f}" '
            f'android:scaleX="{fit:.6f}" android:scaleY="{fit:.6f}">\n'
            f'        <path android:fillColor="{swirl_color}" android:pathData="{swirl}" />\n'
            f'        <group android:translateX="{tx:.3f}" android:translateY="{ty:.3f}" '
            f'android:scaleX="{scale:.4f}" android:scaleY="{scale:.4f}">\n'
            f'            <path android:fillColor="{emblem_color}" android:pathData="{emblem}" />\n'
            "        </group>\n"
            "    </group>\n"
            "</vector>\n"
        )

    background = (
        xml_note(f"The launcher icon's background, Catppuccin Mocha base. {GENERATED.format(source='this script')}")
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        f'    <path android:fillColor="#FF{ICON_BACKGROUND[1:]}" android:pathData="M0,0h108v108h-108z" />\n'
        "</vector>\n"
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + xml_note(GENERATED.format(source="this script"))
        + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        "</adaptive-icon>\n"
    )
    accent, emblem_color = svg_color(svg_text, "Accent"), svg_color(svg_text, "Emblem")
    white = "#FFFFFFFF"
    drawable = OUT_RES / "drawable"
    return {
        drawable / "ic_launcher_background.xml": background,
        drawable / "ic_launcher_foreground.xml": vector(
            "The launcher icon's foreground.", ICON_SIZE, CANVAS, accent, emblem_color
        ),
        drawable / "ic_launcher_monochrome.xml": vector(
            "The themed (monochrome) launcher icon.", ICON_SIZE, CANVAS, white, white
        ),
        drawable / "ic_notification.xml": vector(
            "Status-bar icon for mail notifications; Android draws only its alpha.", SMALL_SIZE, SMALL_CANVAS, white, white
        ),
        OUT_RES / "mipmap-anydpi-v26/ic_launcher.xml": adaptive,
        OUT_RES / "mipmap-anydpi-v26/ic_launcher_round.xml": adaptive,
    }


def render_pictures(icons: Path) -> None:
    """The launcher icon as pictures for Android 7, and the splash logo."""
    for tool in ("rsvg-convert", "magick", "cwebp"):
        if not shutil.which(tool):
            sys.exit(f"brand.py: {tool} is needed for the launcher pictures")
    source = icons / ICON
    with tempfile.TemporaryDirectory() as tmp:

        def logo(size: int) -> Path:
            png = Path(tmp) / f"logo-{size}.png"
            subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(png), str(source)], check=True)
            return png

        for density, size in LEGACY_SIZES.items():
            inner = logo(round(size * 0.68))
            for name, radius in (("ic_launcher", round(size * 0.18)), ("ic_launcher_round", size // 2)):
                # The icon on the Mocha base, as a rounded square or a circle.
                png = Path(tmp) / f"{name}-{size}.png"
                subprocess.run(
                    ["magick", "-size", f"{size}x{size}", "xc:none", "-fill", ICON_BACKGROUND,
                     "-draw", f"roundrectangle 0,0 {size - 1},{size - 1} {radius},{radius}",
                     str(inner), "-gravity", "center", "-composite", *STABLE_PNG, str(png)],
                    check=True,
                )
                out = OUT_RES / f"mipmap-{density}/{name}.webp"
                out.parent.mkdir(parents=True, exist_ok=True)
                subprocess.run(["cwebp", "-quiet", "-lossless", str(png), "-o", str(out)], check=True)
        # The splash logo keeps upstream's layout: the logo in the middle of a transparent square.
        out = OUT_RES / "drawable-xxxhdpi/splashscreen_logo.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            ["magick", "-size", f"{SPLASH_SIZE}x{SPLASH_SIZE}", "xc:none", str(logo(round(SPLASH_SIZE * 0.4))),
             "-gravity", "center", "-composite", *STABLE_PNG, str(out)],
            check=True,
        )
        # The in-app logo. rsvg-convert ignores the icon's prefers-color-scheme rule, so the light variant gets its
        # emblem colour written in.
        svg_text = source.read_text(encoding="utf-8")
        light = re.search(r"prefers-color-scheme: light\)\{\.ColorScheme-Emblem\{color:(#[0-9a-fA-F]{6})\}", svg_text)
        if not light:
            sys.exit("brand.py: no light-mode emblem colour in the icon")
        light_svg = Path(tmp) / "light.svg"
        light_svg.write_text(
            re.sub(r"(\.ColorScheme-Emblem\{color:)#[0-9a-fA-F]{6}", r"\g<1>" + light.group(1), svg_text, count=1),
            encoding="utf-8",
        )
        OUT_ASSETS.mkdir(parents=True, exist_ok=True)
        for name, svg_file in (("logo-dark.png", source), ("logo-light.png", light_svg)):
            subprocess.run(
                ["rsvg-convert", "-w", str(LOGO_SIZE), "-h", str(LOGO_SIZE), "-o", str(OUT_ASSETS / name), str(svg_file)],
                check=True,
            )


# ── Main ──────────────────────────────────────────────────────────────────────────────────────────────────────────


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if anything is out of date")
    parser.add_argument("--icons", type=Path, default=ROOT.parent / "rootiest-icons", help="rootiest-icons checkout")
    args = parser.parse_args()

    outputs = string_outputs() | locale_outputs()
    have_icons = (args.icons / ICON).is_file()
    if have_icons:
        outputs |= icon_outputs(args.icons)
    else:
        print(f"brand.py: {args.icons} has no {ICON}; icons skipped", file=sys.stderr)
    if (args.icons / THEME_CSS).is_file():
        outputs |= theme_outputs(args.icons)
    else:
        print(f"brand.py: {args.icons} has no {THEME_CSS}; theme skipped", file=sys.stderr)

    stale = [path for path, text in outputs.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if have_icons:
        render_pictures(args.icons)
        print("wrote the launcher pictures, the splash logo and the in-app logo")
    return 0


if __name__ == "__main__":
    sys.exit(main())
