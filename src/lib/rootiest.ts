// Rootiest Mail: what differs in the rootiest build (android/app/rootiest.gradle).
// Upstream code reads these in the few places it has to, so merging a new
// Bulwark Mobile release touches as little as possible.

import { NativeModules } from 'react-native';

/**
 * True in the Rootiest Mail build: the rootiest flavor's BulwarkBuild module
 * says so (lib/platform-capabilities reads the same). Read defensively: the
 * i18n code imports this, and tests run it with partial react-native mocks.
 */
export const isRootiest: boolean = (() => {
  try {
    return NativeModules?.BulwarkBuild?.distribution === 'rootiest';
  } catch {
    return false;
  }
})();

/** The app's name, as the launcher shows it (scripts/brand.py). */
export const ROOTIEST_APP_NAME = 'Rootiest Mail';

/** This app's source code. */
export const ROOTIEST_SOURCE_URL = 'https://git.rootiest.dev/rootiest/rootiest-mail-android';

/** Rootiest's own push relay, the default in place of the hosted Bulwark one. */
export const ROOTIEST_RELAY_BASE_URL = 'https://relay.rootiest.dev';

/** Upstream: the app this one is based on (Settings › About). */
export const BULWARK_MOBILE_URL = 'https://github.com/bulwarkmail/native';

/** Rootiest's mail server (Stalwart), where JMAP lives. */
export const ROOTIEST_SERVER_URL = 'https://mail.rootiest.dev';

// RootiestID sign-in in the app: PKCE in the browser against RootiestID with the app's own public client
// ("Rootiest Mail App"). Its id is in Stalwart's acceptedAudiences, so Stalwart takes the access token as it
// takes the webmail's, and the app renews it with RootiestID. Shows in RootiestID as its own app, revocable alone.
export const ROOTIEST_ID_ISSUER = 'https://auth.rootiest.dev';
export const ROOTIEST_ID_CLIENT_ID = '791f9d10-21f5-400d-b58d-96d1abab5a03';
export const ROOTIEST_ID_REDIRECT_URI = 'dev.rootiest.mail://auth/callback';
export const ROOTIEST_ID_SCOPES = 'openid profile email offline_access';

/**
 * A token bundle from the app's own RootiestID sign-in. RootiestID has no revocation endpoint, and ending its
 * browser session at sign-out would sign the user out of every Rootiest service in that browser, so sign-out
 * leaves both alone for these (lib/oauth-native).
 */
export function isRootiestIdToken(tokens: { clientId?: string } | null | undefined): boolean {
  return tokens?.clientId === ROOTIEST_ID_CLIENT_ID;
}

/** The support desk's form for a new ticket. */
export const ROOTIEST_SUPPORT_NEW_URL = 'https://support.rootiest.dev/new';

/**
 * "Report a problem" in the Rootiest build: a new ticket on Rootiest's support desk, filled in as far as a link
 * can (the desk only prefills; the user still reads it and presses Send), instead of an issue on upstream's
 * GitHub, which isn't where problems with this app or its server belong.
 */
export function rootiestSupportUrl(app: { version: string; commit: string }, platform: string): string {
  const body = [
    'What happened?',
    '',
    '',
    'What did you expect?',
    '',
    '',
    '---',
    `App: ${ROOTIEST_APP_NAME} v${app.version} (${app.commit})`,
    `Platform: ${platform}`,
  ].join('\n');
  const params = new URLSearchParams({
    category: 'problem',
    service: 'stalwart',
    subject: `${ROOTIEST_APP_NAME} app: `,
    body,
  });
  return `${ROOTIEST_SUPPORT_NEW_URL}?${params.toString()}`;
}

/**
 * The strings that name the app, naming Rootiest Mail, for a language: merged
 * over upstream's catalogs in src/i18n. Generated by scripts/brand.py.
 */
export function rootiestStrings(locale: string): Record<string, unknown> {
  const all = require('../../locales/rootiest/strings.json') as Record<string, Record<string, unknown>>;
  return all[locale] ?? {};
}
